import { expect, test } from '@playwright/test'

test('one Lodestar expedition, with crew rooms and no Classic Voyage route', async ({ page }) => {
  await page.goto('/?classic')
  await expect(page.getByRole('heading', { name: /starship explorer/i })).toBeVisible()
  await expect(page.getByText('ISS LODESTAR')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Take command' })).toHaveCount(0)
  await expect(page.getByText(/Classic voyage/i)).toHaveCount(0)
  await page.getByRole('textbox').fill('first-lodestar-voyage')
  await page.getByRole('button', { name: 'Begin expedition', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Exploration stations' })).toBeVisible()
  await expect(page.getByText('Alexander Vale').first()).toBeVisible()
  await page.getByRole('button', { name: 'Visit the bridge' }).click()
  await expect(page.getByRole('heading', { name: 'The bridge' })).toBeVisible()
  await expect(page.getByText('Alexander Vale').last()).toBeVisible()
  await page.getByRole('button', { name: /Morozova/ }).click()
  await expect(page.getByRole('heading', { name: 'Science deck' })).toBeVisible()
  await page.getByRole('button', { name: 'Open research lab' }).click()
  await expect(page.getByRole('button', { name: /Research lab/ }).first()).toHaveAttribute('aria-current', 'page')
})
