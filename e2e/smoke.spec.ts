import { expect, test } from '@playwright/test'

test('one Lodestar expedition, with crew rooms and no Classic Voyage route', async ({ page }) => {
  await page.goto('/?classic')
  await expect(page.getByRole('heading', { name: /starship explorer/i })).toBeVisible()
  await expect(page.getByText('ISS LODESTAR')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Take command' })).toHaveCount(0)
  await expect(page.getByText(/Classic voyage/i)).toHaveCount(0)
  await page.getByRole('textbox').fill('first-lodestar-voyage')
  await page.getByRole('button', { name: 'Begin expedition', exact: true }).click()
  await page.getByRole('button', { name: 'Skip briefing' }).click()
  await expect(page.getByRole('navigation', { name: 'Exploration stations' })).toBeVisible()
  await expect(page.getByText('Alexander Vale').first()).toBeVisible()
  await page.getByRole('button', { name: 'Visit the bridge' }).click()
  await expect(page.getByRole('heading', { name: 'The bridge' })).toBeVisible()
  await expect(page.getByText('Alexander Vale').last()).toBeVisible()
  await page.getByRole('button', { name: /Morozova/ }).click()
  await expect(page.getByRole('heading', { name: 'Science deck' })).toBeVisible()
  await page.getByRole('button', { name: 'Open research lab' }).click()
  await expect(page.getByRole('button', { name: /Research lab/ }).first()).toHaveAttribute('aria-current', 'page')
})

test('new captains see a three-part context briefing and can skip, while resumes skip it', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Begin expedition' }).click()
  await expect(page.getByRole('heading', { name: 'These are not our stars.' })).toBeVisible()
  await expect(page.getByText(/experimental transit aperture/)).toBeVisible()
  await page.getByRole('button', { name: 'Continue briefing' }).click()
  await expect(page.getByRole('heading', { name: 'One ship. Limited supplies.' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue briefing' }).click()
  await expect(page.getByRole('heading', { name: 'Find a way home.' })).toBeVisible()
  await page.getByRole('button', { name: 'Take command' }).click()
  await expect(page.getByRole('navigation', { name: 'Exploration stations' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Resume expedition' }).click()
  await expect(page.getByRole('heading', { name: 'These are not our stars.' })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Exploration stations' })).toBeVisible()
})

test('mining tug report appears in its own dossier, never replacing the location scene', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Begin expedition' }).click()
  await page.getByRole('button', { name: 'Skip briefing' }).click()
  await page.getByRole('button', { name: 'Survey system · 1 day' }).click()
  await page.getByTestId('location-resource-field').first().click()
  await expect(page.getByTestId('report-image-tethered-tug')).toHaveCount(0)
  await page.getByRole('button', { name: 'Investigate · 1 day' }).click()
  const report = page.getByTestId('report-image-tethered-tug')
  await expect(report).toBeVisible()
  await expect(report.locator('img')).toHaveAttribute('src', '/assets/reports/mining-tug.svg')
  await expect(page.locator('.exp-scene-art')).not.toHaveAttribute('src', /mining-tug/)
  await expect(page.getByRole('button', { name: /Transfer propellant/ })).toBeVisible()
})
