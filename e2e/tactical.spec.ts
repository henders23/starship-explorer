import { expect, test } from '@playwright/test'
import { completeBoarding, deployBoarding } from '../tools/tactical-walkthrough.js'
import { createCampaign, reduceCampaign } from '../src/engine/exploration/campaign.js'
import type { Campaign } from '../src/engine/exploration/campaign.js'
import { EXPLORATION_SAVE_KEY, saveExploration } from '../src/ui/exploration-save.js'
function envelope(s: Campaign) { let raw = ''; saveExploration(s, { getItem: () => null, removeItem: () => {}, setItem: (_, v) => { raw = v } }); return raw }

test('boards from a location, issues orders, resumes combat and safely retreats', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', (e) => errors.push(e.message))
  const deployed = deployBoarding('browser-boarding')
  let ready = createCampaign(deployed.seed)
  for (const action of deployed.actions.slice(0, -1)) ready = reduceCampaign(ready, action)
  await page.addInitScript(({ key, raw }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, raw) }, { key: EXPLORATION_SAVE_KEY, raw: envelope(ready) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Resume expedition', exact: true }).click()
  await page.getByTestId('location-derelict').filter({ hasText: 'Silent Courier' }).click()
  await page.getByRole('button', { name: 'Board with away team · tactical mission' }).click()
  await expect(page.getByRole('dialog', { name: 'Away team', exact: true })).toContainText('4/4 selected')
  await page.getByRole('button', { name: 'Deploy away team', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Boarding operation' })).toBeVisible()
  await page.getByRole('button', { name: 'Tile 3,4', exact: true }).click()
  await page.getByRole('button', { name: 'Move · 1 AP', exact: true }).click()
  await expect(page.locator('.tac-orders')).toContainText('1/2 AP')
  await page.getByRole('button', { name: /Custodian 1.*HP/ }).click()
  await page.screenshot({ path: info.outputPath('boarding-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Fire · 1 AP', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Fire · 1 AP', exact: true })).toBeDisabled()
  await page.reload()
  await page.getByRole('button', { name: 'Resume expedition', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Boarding operation' })).toBeVisible()
  await expect(page.locator('.tac-orders')).toContainText('0/2 AP')
  await page.getByRole('button', { name: 'Extract team', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Confirm extraction' })).toContainText('Permanently lost if you leave now: Mara Chen')
  await page.getByRole('button', { name: 'Keep the shuttle waiting' }).click()
  await page.getByRole('button', { name: 'End turn · hostiles act' }).click()
  await page.getByRole('button', { name: 'Tile 2,4 shuttle', exact: true }).click()
  await page.getByRole('button', { name: 'Move · 1 AP', exact: true }).click()
  await page.getByRole('button', { name: 'Extract team', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm safe extraction' }).click()
  await expect(page.getByRole('heading', { name: 'Another way in.' })).toBeVisible()
  await page.getByRole('button', { name: 'Return to the Ithaca' }).click()
  await page.getByRole('button', { name: 'Away team', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Away team', exact: true })).toContainText('1 missions')
  expect(errors).toEqual([])
})

test('mobile movement, objective extraction, reward and debrief reload', async ({ page }, info) => {
  const run = completeBoarding('boarding-sweep-0')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(({ key, raw }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, raw) }, { key: EXPLORATION_SAVE_KEY, raw: envelope(run.extraction!) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Resume expedition', exact: true }).click()
  await expect(page.locator('.tac-objective')).toContainText('Core secured')
  await page.getByRole('button', { name: 'Enlarge map', exact: true }).click()
  await expect(page.locator('.tac-scroll')).toHaveClass(/expanded/)
  await page.getByRole('button', { name: 'Fit map', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('boarding-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Extract team', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm safe extraction' }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Resume expedition', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Something worth bringing home.' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('boarding-debrief-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Return to the Ithaca' }).click()
  await page.getByRole('button', { name: /Discoveries/ }).click()
  await expect(page.locator('.exp-main')).toContainText('Exotic energy')
  await page.reload()
  await page.getByRole('button', { name: 'Resume expedition', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Beyond the familiar' })).toBeVisible()
})
